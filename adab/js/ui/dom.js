export function icon(name, cls) {
  const svg = document.createElementNS(SVG_NS, 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('focusable', 'false');
  if (cls) svg.setAttribute('class', cls);
  const path = document.createElementNS(SVG_NS, 'path');
  path.setAttribute('d', PATHS[name]);
  path.setAttribute('fill', 'currentColor');
  svg.append(path);
  return svg;
}

/** A Pashto text with [[left-to-right pieces]] and {name} slots (filled from `slots`) as DOM nodes. */
export function rich(text, slots = {}) {
  const out = [];
  for (const part of text.split(/(\[\[[^\]]+\]\]|\{[a-z]+\})/)) {
    if (!part) continue;
    if (part.startsWith('[[')) out.push(h('bdi', { class: 'latin', dir: 'ltr' }, part.slice(2, -2)));
    else if (part.startsWith('{')) out.push(slots[part.slice(1, -1)] || '');
    else out.push(part);
  }
  return out;
}

/** A date or a number kept left-to-right inside Pashto text (otherwise "2026-11-27" shows as "27-11-2026"). */
export function ltr(text) {
  return h('bdi', { dir: 'ltr' }, text);
}

/** "yyyy-MM-dd HH:mm" in the phone's time zone, like the Android app. */
export function formatMillis(ms) {
  if (!Number.isFinite(ms)) return '';
  const d = new Date(ms);
  const p = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())} ${p(d.getHours())}:${p(d.getMinutes())}`;
}
